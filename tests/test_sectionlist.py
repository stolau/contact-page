_LI_TOKEN = re.compile(r"<li\b|</li\s*>", re.IGNORECASE)


def outer_li(html, section_id):
    """The whole <li class="section-row" data-section-id="N"> … </li>.

    Depth-aware on purpose: fact_card and service_card emit <li>, so the hero
    and palvelut rows nest lists inside their preview cards and a naive scan to
    the first </li> truncates them (measured: hero 2411 of 3767 bytes). The
    tietoa row happens to have none today, but a ⋯ menu rendered as list items
    would give it some tomorrow.
    """
    start = html.index(f'<li class="section-row" data-section-id="{section_id}"')
    depth = 0
    for match in _LI_TOKEN.finditer(html, start):
        if match.group(0).startswith("</"):
            depth -= 1
            if depth == 0:
                return html[start : match.end()]
        else:
            depth += 1
    raise AssertionError(f"unclosed <li> for section {section_id}")


