def css_rules(text):
    """(selector list, declaration block) for every rule, comments stripped."""
    body = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    rules = []
    for chunk in body.split("}"):
        if "{" not in chunk:
            continue
        selectors, declarations = chunk.split("{", 1)
        rules.append((selectors.strip(), declarations.strip()))
    return rules


JINJA_TAG = re.compile(r"\{%.*?%\}|\{\{.*?\}\}", re.DOTALL)


def hidden_classes(template):
    """Every class on an element this unit server-renders with `hidden`.

    Jinja tags are stripped before the parse, and that is load-bearing rather
    than tidy. `class="add-section-reason"{% if offerable %} hidden{% endif %}`
    reaches HTMLParser as the attribute `hidden{%` — the attribute-name
    pattern runs on to the brace — so an element hidden on a CONDITION was
    invisible to this guard while an unconditionally hidden one was not.
    Stripping the tags reads both the same way, which is the conservative
    reading: an element that is ever rendered hidden needs the stylesheet to
    mean it.

    Raises rather than returning an empty set. The guard below derives its
    subjects from the very templates it protects, so a template that renders
    nothing hidden any more makes the guard vacuous instead of red — the
    failure mode the two menus already demonstrated. Both templates hold at
    least one hidden element by design (the expanded editor, the add menu),
    so none is a fact worth reporting quietly.
    """

    class _Hidden(HTMLParser):
        def __init__(self):
            super().__init__(convert_charrefs=True)
            self.classes = set()

        def handle_starttag(self, tag, attrs):
            attributes = dict(attrs)
            if "hidden" in attributes:
                self.classes.update((attributes.get("class") or "").split())

    parser = _Hidden()
    source = (ROOT / template).read_text(encoding="utf-8")
    parser.feed(JINJA_TAG.sub("", JINJA_COMMENT.sub("", source)))
    assert parser.classes, f"{template} renders nothing hidden — the guard" \
        " built from it would assert nothing"
    return parser.classes


def test_an_element_rendered_hidden_is_actually_hidden():
    """An author `display:` beats the UA sheet's `[hidden] { display: none }`
    whatever its specificity, so a stylesheet that gives such an element a
    display and never mentions [hidden] silently un-hides it.

    This is not theoretical. It shipped: .row-menu-items and
    .add-section-menu both set `display: flex`, so all six row menus were
    drawn permanently open, each one covering the right-hand end of the row
    beneath it. Five of the six rows' Muokkaa and ⋯ buttons were unclickable
    with a real mouse, and toggleMenu's `hidden = !opening` changed nothing
    on screen. Every server-side test passed throughout, because none of them
    computes a style — this one reads the rule instead.
    """
    css = css_rules((ROOT / "app" / "static" / "sections.css").read_text(
        encoding="utf-8"))
    blanket = any(
        selector.strip() == "[hidden]" and "display: none" in declarations
        for selector, declarations in css
    )
    styled = set()
    guarded = set()
    for selector, declarations in css:
        display = re.search(r"display:\s*([\w-]+)", declarations)
        for part in selector.split(","):
            part = part.strip()
            match = re.fullmatch(r"\.([\w-]+)(\[hidden\])?", part)
            if not match:
                continue
            name, on_hidden = match.group(1), match.group(2)
            if on_hidden:
                if display and display.group(1) == "none":
                    guarded.add(name)
            elif display and display.group(1) != "none":
                styled.add(name)

    rendered_hidden = hidden_classes(
        "app/templates/_section_row.html"
    ) | hidden_classes("app/templates/edit_sections.html")
    unhidden = sorted((styled & rendered_hidden) - guarded) if not blanket else []
    assert not unhidden, (
        f"{unhidden} are rendered with `hidden` but given a display that"
        " overrides it"
    )


