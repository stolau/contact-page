def document_scripts(html):
    """Every <script> of the document in source order: an inline one by its
    id, an external one by its filename.

    The inline #bootstrap blob is included because it, too, is load-bearing
    order — sectionlist.js reads document.getElementById("bootstrap") at parse
    time, so a bootstrap moved below it throws before a single row is wired."""

    class _Scripts(HTMLParser):
        def __init__(self):
            super().__init__(convert_charrefs=True)
            self.names = []

        def handle_starttag(self, tag, attrs):
            if tag != "script":
                return
            attributes = dict(attrs)
            src = attributes.get("src")
            if src:
                self.names.append(src.rsplit("/", 1)[-1])
            elif attributes.get("id"):
                self.names.append(attributes["id"])

    parser = _Scripts()
    parser.feed(html)
    return parser.names


# Strings first, so a "//" inside one is eaten as string and never mistaken
# for a comment. No file here uses a regex literal, which this would misread.
JS_STRING_OR_COMMENT = re.compile(
    r'"(?:\\.|[^"\\])*"'
    r"|'(?:\\.|[^'\\])*'"
    r"|`(?:\\.|[^`\\])*`"
    r"|/\*.*?\*/"
    r"|//[^\n]*",
    re.DOTALL,
)


def strip_js_comments(source):
    """The source with comments blanked and every newline kept, so offsets
    stay on their own lines. Required because sectionlist.js's header comment
    names window.createSectionForm and window.createAutosave.DELAY in prose,
    and a guard that reads prose is a guard that cannot fail."""

    def blank(match):
        text = match.group(0)
        if text.startswith(("/*", "//")):
            return "\n" * text.count("\n")
        return text

    return JS_STRING_OR_COMMENT.sub(blank, source)


