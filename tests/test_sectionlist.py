def order_body(case, ids):
    """The refused bodies, each built from the real ids the store holds.

    Every id list here is *reversed* first, deliberately. A refused list in
    ascending order would write the positions the rows already have, so an
    endpoint that wrote before it validated would leave the table looking
    untouched and the transactional claim would pass without being tested.
    """
    backwards = list(reversed(ids))
    return {
        # A partial list is a lost row, not a smaller write.
        "partial": {"ids": backwards[:-1]},
        # Right length, but one row named twice and one not at all. Note
        # this is caught by the set-equality check, not the duplicate one —
        # the dropped row is enough on its own.
        "duplicate": {"ids": [backwards[0]] + backwards[1:-1] + [backwards[0]]},
        # Every id present and one of them twice, so the set still matches
        # every known row and only the duplicate check can refuse it. The
        # case that makes that check reachable: without it this body is
        # accepted 200 and writes a seventh position.
        "over-long": {"ids": backwards + [backwards[0]]},
        "unknown-id": {"ids": backwards[:-1] + [9999]},
        "not-a-list": {"ids": "1,2,3"},
        "missing-ids": {},
        "string-ids": {"ids": [str(i) for i in backwards]},
        # bool is an int in Python; it is not a section id.
        "boolean-id": {"ids": [True] + backwards[1:]},
        "not-an-object": ["a", "list", "at", "the", "top", "level"],
    }[case]


NOT_WHOLE = "listassa on oltava jokainen osio täsmälleen kerran"
MALFORMED = "ids puuttuu tai ei ole lista kokonaislukuja"


@pytest.mark.parametrize(
    "case,reason",
    [
        ("partial", NOT_WHOLE),
        ("duplicate", NOT_WHOLE),
        ("over-long", NOT_WHOLE),
        ("unknown-id", NOT_WHOLE),
        ("not-a-list", MALFORMED),
        ("missing-ids", MALFORMED),
        ("string-ids", MALFORMED),
        ("boolean-id", MALFORMED),
        ("not-an-object", MALFORMED),
    ],
)
def test_a_refused_reorder_writes_nothing(logged_in_admin, app, case, reason):
    """The whole order arrives or nothing does. Each refusal is checked against
    the positions the store holds either side, not against the response alone —
    a 400 that had already rewritten half the table would pass otherwise.

    The reason is asserted per case rather than merely being truthy: a body
    that never parsed answers "malformed" too, so a harness that mangled its
    own JSON would otherwise show eight green refusals having tested one.
    """
    before = positions(app)
    body = order_body(case, [r["id"] for r in section_rows(app)])

    response = logged_in_admin.put(
        "/api/sections/order", json=body, headers=JSON_ACCEPT
    )

    assert response.status_code == 400
    assert response.get_json()["error"] == reason
    assert positions(app) == before


def test_the_full_order_reversed_reorders_the_screen_and_the_public_page(
    logged_in_admin, app
):
    before = kinds_in_position_order(app)
    ids = [r["id"] for r in section_rows(app)]

    response = put_order(logged_in_admin, list(reversed(ids)))
    assert response.status_code == 200

    assert kinds_in_position_order(app) == list(reversed(before))
    assert positions(app) == {
        section_id: place
        for place, section_id in enumerate(reversed(ids), start=1)
    }

    # The screen re-reads it …
    html = logged_in_admin.get("/muokkaa/osiot").get_data(as_text=True)
    rendered = re.findall(r'<li class="section-row" data-section-id="(\d+)"',
                          html)
    assert [int(i) for i in rendered] == list(reversed(ids))

    # … and so does the public page, sections and nav both (page.html:110-127).
    public = public_html(app)
    section_order = re.findall(r'<section id="([a-z]+)"', public)
    assert section_order == ["sijainti", "yhteydenotto", "vastaanotto",
                             "palvelut", "tietoa", "hero"]
    nav = element_text(public, "nav", "nav-links")
    assert nav.index("Sijainti") < nav.index("Vastaanotto") < nav.index("Tietoa")


